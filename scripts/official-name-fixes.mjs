const HANGUL = /[ㄱ-ㆎ가-힣]/;

/** 공식 명칭으로 쓸 값인지(값이 있고, 한글이 섞이지 않았고, 다른 항목이 아니다) */
export function isOfficialName(lang, id, value) {
  return (
    typeof value === "string" &&
    value.trim() !== "" &&
    !HANGUL.test(value) &&
    !Object.hasOwn(WRONG_OFFICIAL_NAMES[lang] ?? {}, id)
  );
}
