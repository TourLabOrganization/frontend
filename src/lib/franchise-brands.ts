const BRANDS = FRANCHISE_BRANDS.map((b) => b.replace(/\s/g, "").toLowerCase());

/**
 * 전국 체인 브랜드 가게인지: 이름의 「/」 앞부분(없으면 이름 전체)에서 공백을 뺀 값이 브랜드로 시작하면(대소문자 무시).
 * 「CGV용산아이파크몰」 · 「맥도날드/신월남부DT점」 · 「스타벅스/경주보문로DT점」. 겹치는 브랜드(이마트 · 이마트24)는 어느 쪽이든 걸린다.
 * 영문자로 끝나는 브랜드는 바로 뒤가 영문자면 다른 이름으로 본다(「CU」가 「CUBE」를 거르지 않게)
 */
export function isFranchiseName(name: string): boolean {
  const head = name.split("/")[0].replace(/\s/g, "").toLowerCase();
  return BRANDS.some((brand) => {
    if (!head.startsWith(brand)) return false;
    const next = head.charAt(brand.length);
    return !(/[a-z]$/.test(brand) && /[a-z]/.test(next));
  });
}
