/** PoC krUnits. locale이 ko이거나 규칙이 없는 언어면 원문 그대로 */
export function krUnits(text: string, locale: string): string {
  const rules = KR_UNIT[locale];
  if (!rules || !/[가-힣]/.test(text)) return text;
  let out = text;
  for (const [re, to] of rules) out = out.replace(re, to);
  return out
    .replace(/\s{2,}/g, " ")
    .replace(/\(\s*\)/g, "")
    .trim();
}
